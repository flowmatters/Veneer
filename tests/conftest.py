"""Live fixtures: a VeneerCmd serving the generated synthetic model.

Needs VENEER_CMD_EXE (the built FlowMatters.Source.VeneerCmd.exe); without it every test that
uses a live fixture is skipped. Optional: VENEER_TEST_PORT (default 9890) and
VENEER_SOURCE_DIR (passed as VeneerCmd's -d when it cannot find Source on its own). The model
is tests/fixtures/evaluate-model.rsproj, generated by tests/fixtures/build_evaluate_model.py.

Two modes, one VeneerCmd per pytest invocation (both use the same port):
- default: the `veneer` fixture, whose scenario has run once (a short warm-up run);
- VENEER_COLD=1: the `veneer_cold` fixture, whose scenario is loaded but has NEVER run in the
  process. Every test that uses the other mode's fixture is skipped. Run both:

      pytest tests/test_functions_evaluate.py
      VENEER_COLD=1 pytest tests/test_functions_evaluate.py
"""
import collections
import contextlib
import os

import pytest
import requests

from tests.live import port_in_use, rsproj_identity_hits, veneer_cmd

FIXTURES = os.path.join(os.path.dirname(os.path.abspath(__file__)), "fixtures")
MODEL = os.path.join(FIXTURES, "evaluate-model.rsproj")

# Every committed fixture, and the generator that writes it scrubbed.
COMMITTED_FIXTURES = {
    MODEL: "build_evaluate_model.py",
    os.path.join(FIXTURES, "recorder-sets-model.rsproj"): "build_recorder_sets_model.py",
}

# base_url and port as before; log_path is VeneerCmd's captured stdout/stderr.
LiveVeneer = collections.namedtuple("LiveVeneer", ["base_url", "port", "log_path"])


def pytest_sessionstart(session):
    """The committed fixtures are published: refuse to run at all if any of their text members
    names this machine, its user or a local path (Source writes the saving user into the project;
    the generators scrub it — this stops a regeneration without the scrub from slipping through)."""
    for fixture, generator in COMMITTED_FIXTURES.items():
        if os.path.exists(fixture):
            hits = rsproj_identity_hits(fixture)
            if hits:
                pytest.exit(f"{fixture} identifies a machine, user or local path: {hits}; "
                            f"regenerate it with tests/fixtures/{generator} (which scrubs them)",
                            returncode=1)


def cold_mode() -> bool:
    return os.environ.get("VENEER_COLD", "") not in ("", "0")


@contextlib.contextmanager
def served_model(tmp_path_factory):
    """Start VeneerCmd on MODEL (skipping the test when that is not possible) and kill it on
    exit."""
    exe = os.environ.get("VENEER_CMD_EXE")
    if not exe:
        pytest.skip("VENEER_CMD_EXE is not set; live Veneer tests skipped")
    if not os.path.exists(MODEL):
        pytest.skip(f"{MODEL} is missing; generate it with tests/fixtures/build_evaluate_model.py")
    port = int(os.environ.get("VENEER_TEST_PORT", "9890"))
    if port_in_use(port):
        # A failure, not a skip: something else is listening where the tests would talk, and a
        # green run that tested nothing must not be mistaken for a pass.
        pytest.fail(f"port {port} is already in use; set VENEER_TEST_PORT to a free port")

    from veneer import manage
    log_dir = tmp_path_factory.mktemp("veneer-log")
    procs, ports, log_paths = manage.start(project_fn=MODEL, ports=port, script=True,
                                           veneer_exe=veneer_cmd(exe), quiet=True,
                                           return_log_paths=True,
                                           capture_output_dir=str(log_dir))
    print(f"\nstarted VeneerCmd pid(s) {[p.pid for p in procs]} on port {port}")
    try:
        if ports[0] != port:
            pytest.fail(f"VeneerCmd bound port {ports[0]}, not {port}")
        yield LiveVeneer(f"http://localhost:{port}", port, log_paths[0])
    finally:
        manage.kill_all_now(procs)
        print(f"\nkilled VeneerCmd pid(s) {[p.pid for p in procs]}")


@pytest.fixture(scope="session")
def veneer(tmp_path_factory):
    """A scenario that has run once. The evaluate endpoint answers the same with or without a
    run (see the cold tests); this mode is where the run-dependent state — function values,
    usage targets, run results — exists for the no-mutation test to check."""
    if cold_mode():
        pytest.skip("VENEER_COLD is set: this invocation serves a never-run scenario")
    with served_model(tmp_path_factory) as live:
        run = requests.post(f"{live.base_url}/runs",
                            json={"StartDate": "01/01/2000", "EndDate": "05/01/2000"},
                            timeout=300)
        assert run.status_code == 200, run.text
        yield live


@pytest.fixture(scope="module")
def veneer_cold(tmp_path_factory):
    """A scenario loaded but never run in this process: no warm-up run, and nothing in the
    tests that use it may start one."""
    if not cold_mode():
        pytest.skip("cold-scenario tests need VENEER_COLD=1 (a separate pytest invocation)")
    with served_model(tmp_path_factory) as live:
        yield live

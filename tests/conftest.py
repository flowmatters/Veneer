"""Live fixtures: a VeneerCmd serving the generated synthetic model.

Needs VENEER_CMD_EXE (the built FlowMatters.Source.VeneerCmd.exe); without it every test that
uses the `veneer` fixture is skipped. Optional: VENEER_TEST_PORT (default 9890) and
VENEER_SOURCE_DIR (passed as VeneerCmd's -d when it cannot find Source on its own). The model
is tests/fixtures/evaluate-model.rsproj, generated by tests/fixtures/build_evaluate_model.py.
"""
import collections
import os

import pytest
import requests

from tests.live import evaluate, make_item, port_in_use, veneer_cmd

MODEL = os.path.join(os.path.dirname(os.path.abspath(__file__)),
                     "fixtures", "evaluate-model.rsproj")

# base_url and port as before; log_path is VeneerCmd's captured stdout/stderr.
LiveVeneer = collections.namedtuple("LiveVeneer", ["base_url", "port", "log_path"])

# What the endpoint answers BEFORE the scenario has ever run, captured by the `veneer` fixture
# before its warm-up run (see test_now_honours_the_items_date_before_any_run).
COLD_NOW_ITEMS = [make_item("jul", "$Now.Month*100+$Now.Day", "2001-07-01")]
cold_probe = {}


@pytest.fixture(scope="session")
def veneer(tmp_path_factory):
    exe = os.environ.get("VENEER_CMD_EXE")
    if not exe:
        pytest.skip("VENEER_CMD_EXE is not set; live Veneer tests skipped")
    if not os.path.exists(MODEL):
        pytest.skip(f"{MODEL} is missing; generate it with tests/fixtures/build_evaluate_model.py")
    port = int(os.environ.get("VENEER_TEST_PORT", "9890"))
    if port_in_use(port):
        pytest.skip(f"port {port} is already in use; set VENEER_TEST_PORT to a free port")

    from veneer import manage
    log_dir = tmp_path_factory.mktemp("veneer-log")
    procs, ports, log_paths = manage.start(project_fn=MODEL, ports=port, script=True,
                                           veneer_exe=veneer_cmd(exe), quiet=True,
                                           return_log_paths=True,
                                           capture_output_dir=str(log_dir))
    try:
        if ports[0] != port:
            pytest.fail(f"VeneerCmd bound port {ports[0]}, not {port}")
        base_url = f"http://localhost:{port}"
        cold_probe["now"] = evaluate(base_url, COLD_NOW_ITEMS)
        # Warm up with a short run, for two reasons. A function reference reads the function's
        # current value, which is 0 until a run computes it (Source's behaviour, by design).
        # And, observed: on a scenario that has been loaded but never run, $Now evaluates to 0
        # (see test_now_honours_the_items_date_before_any_run); suspected cause, the function
        # manager's per-run state is only set up by a run (under investigation). The other
        # tests exercise the endpoint against a scenario that has run.
        run = requests.post(f"{base_url}/runs",
                            json={"StartDate": "01/01/2000", "EndDate": "05/01/2000"},
                            timeout=300)
        assert run.status_code == 200, run.text
        yield LiveVeneer(base_url, port, log_paths[0])
    finally:
        manage.kill_all_now(procs)

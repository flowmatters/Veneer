"""Live fixtures: a VeneerCmd serving the generated synthetic model.

Needs VENEER_CMD_EXE (the built FlowMatters.Source.VeneerCmd.exe); without it every test that
uses the `veneer` fixture is skipped. Optional: VENEER_TEST_PORT (default 9890) and
VENEER_SOURCE_DIR (passed as VeneerCmd's -d when it cannot find Source on its own). The model
is tests/fixtures/evaluate-model.rsproj, generated by tests/fixtures/build_evaluate_model.py.
"""
import os
import socket

import pytest
import requests

MODEL = os.path.join(os.path.dirname(os.path.abspath(__file__)), "fixtures", "evaluate-model.rsproj")

# Must match TransientFunctionEvaluator.TRANSIENT_NAME.
TRANSIENT_NAME = "$f_veneer_evaluate"

STRAY_SCRIPT = '''
fm = scenario.Network.FunctionManager
n = 0
for t in list(fm.Functions) + list(fm.Variables):
    n += sum(1 for x in t.ReferencingFunctions if str(x.Name) == "%s")
result = str(n)
''' % TRANSIENT_NAME

# What the endpoint answers BEFORE the scenario has ever run, captured by the `veneer` fixture
# before its warm-up run (see test_now_honours_the_items_date_before_any_run).
COLD_NOW_ITEMS = [{"id": "jul", "date": "2001-07-01", "expression": "$Now.Month*100+$Now.Day"}]
cold_probe = {}


def port_in_use(port: int) -> bool:
    with socket.socket(socket.AF_INET, socket.SOCK_STREAM) as s:
        s.settimeout(1.0)
        return s.connect_ex(("127.0.0.1", port)) == 0


def veneer_cmd(exe: str) -> str:
    """The VeneerCmd command for manage.start, with -d when VENEER_SOURCE_DIR is set
    (manage.start has no option for it, but places veneer_exe verbatim at the head of the
    command line)."""
    source_dir = os.environ.get("VENEER_SOURCE_DIR")
    return f'"{exe}" -d "{source_dir}"' if source_dir else f'"{exe}"'


def evaluate(base_url, items, timeout=120):
    """POST /functions/evaluate; returns (status, parsed JSON body or None)."""
    r = requests.post(f"{base_url}/functions/evaluate", json={"items": items}, timeout=timeout)
    try:
        body = r.json()
    except ValueError:
        body = None
    return r.status_code, body


def stray_count(base_url) -> int:
    """How many ReferencingFunctions sets still hold the endpoint's transient function."""
    r = requests.post(f"{base_url}/ironpython", json={"Script": STRAY_SCRIPT}, timeout=60)
    r.raise_for_status()
    body = r.json()
    assert not body.get("Exception"), body["Exception"]
    return int(body["Response"]["Value"])


@pytest.fixture(scope="session")
def veneer():
    exe = os.environ.get("VENEER_CMD_EXE")
    if not exe:
        pytest.skip("VENEER_CMD_EXE is not set; live Veneer tests skipped")
    if not os.path.exists(MODEL):
        pytest.skip(f"{MODEL} is missing; generate it with tests/fixtures/build_evaluate_model.py")
    port = int(os.environ.get("VENEER_TEST_PORT", "9890"))
    if port_in_use(port):
        pytest.skip(f"port {port} is already in use; set VENEER_TEST_PORT to a free port")

    from veneer import manage
    procs, ports, _logs = manage.start(project_fn=MODEL, ports=port, script=True,
                                       veneer_exe=veneer_cmd(exe), quiet=True,
                                       return_log_paths=True)
    try:
        if ports[0] != port:
            pytest.fail(f"VeneerCmd bound port {ports[0]}, not {port}")
        base_url = f"http://localhost:{port}"
        cold_probe["now"] = evaluate(base_url, COLD_NOW_ITEMS)
        # Warm up: a freshly loaded scenario has never been through a run's
        # FunctionManager.Reset, and evaluates $Now/$Start, lookups and modelled variables
        # wrongly until it has (see test_now_honours_the_items_date_before_any_run). The tests
        # exercise the endpoint against a scenario that has run, as one whose results a caller
        # is evaluating against will have.
        run = requests.post(f"{base_url}/runs", json={"StartDate": "01/01/2000", "EndDate": "05/01/2000"},
                            timeout=300)
        assert run.status_code == 200, run.text
        yield base_url, port
    finally:
        manage.kill_all_now(procs)
